---@param statstring string Raw statstring from ECItem
---@param typestring string "DefaultBoosts"|"Boosts"|"Passives"|etc.
---@param treeParent ExtuiTreeParent tooltip usually, to add to
function StatBS:PresentStat(statstring, typestring, treeParent)
    statstring = statstring:gsub(" ", "")
    local b = StatBS:SplitStatString(statstring) or {}
    local statlabel = treeParent:AddText(string.format("%s:", typestring))
    statlabel:SetColor("Text", Imgui.Colors.Tan)
    statlabel:SetStyle("ItemSpacing", 0)
    local itable = treeParent:AddTable(string.format("itable%s", typestring), 2)
    itable.SizingFixedFit = true
    --itable.Borders = true
    --itable.NoHostExtendX = true
    local irow = itable:AddRow()
    irow:AddCell().ItemWidth = 4 -- indent cell
    local statcell = irow:AddCell()
    itable:SetStyle("ItemSpacing", 0)
    if typestring == "Passives" then
        -- passives may be more complicated?
        if table.isEmpty(b) then
            statcell:AddBulletText("None")
        else
            for _,v in ipairs(b) do
                local passive = Ext.Stats.Get(v) --[[@as PassiveData]]
                if passive ~= nil then
                    local success = pcall(function() return passive.Properties ~= nil end)
                    if success then
                        local st = statcell:AddText(StatBS:StripLSTags(Ext.Loca.GetTranslatedString(passive.DisplayName)))
                        st:SetColor("Text", Imgui.Colors.Tan)
                        if StatBS:CheckPassiveContains(passive.Properties, "IsHidden") then
                            st.Label = st.Label.." [Hidden]"
                        end
                        local parsed = StatBS:ReplaceDescParams(StatBS:StripLSTags(Ext.Loca.GetTranslatedString(passive.Description)), passive)
                        local ptable = statcell:AddTable(string.format("ptable%s", v), 2)
                        ptable.SizingFixedFit = true
                        --ptable.Borders = true
                        ptable.NoHostExtendX = true
                        local prow = ptable:AddRow()
                        prow:AddCell().ItemWidth = 2 -- indent cell
                        prow:AddCell():AddBulletText(wrap(parsed, 50))
                    else
                        -- ECDebug("Couldn't display passive")
                        -- ECDumpS(passive)
                    end
                end
            end
        end
    else
        if table.isEmpty(b) then
            statcell:AddBulletText("None")
        else
            -- boosts and whatever else
            for i,v in ipairs(b) do
                v = StatBS:CheckForCriticalHitBoost(v) -- weird
                local c = StatBS:CheckForStatConditional(v) -- why not
                local parsed = StatBS:ParseKnownFunctions(StatBS:SplitFunctionString(v)) -- yikes
                statcell:AddBulletText(wrap(c ~= nil and c or parsed ~= nil and parsed or v, 60))
            end
        end
    end
end
  
