function wrap(text, width, maxnewlines)
    local tail, lines = text.." ", {}
    while tail do
        lines[#lines + 1], tail = tail
            :gsub("^%s+", "")
            :gsub(char_pattern, "\0%0\0", width)
            :gsub("%z%z", "")
            :gsub("(%S)%z(%s)", "%1%2\0")
            :gsub("^(%z[^\r\n%z]*)%f[%s](%Z*)%z(.*)$", "%1\0%2%3")
            :match"^%z(%Z+)%z(.*)$"
    end
    if maxnewlines ~= nil then
        if #lines <= maxnewlines then
            return table.concat(lines, "\n", 1, math.min(#lines, maxnewlines))
        else
            return table.concat(lines, "\n", 1, math.min(#lines, maxnewlines)).."..."
        end
    end
    return table.concat(lines, "\n")
end
