function StatBS:ReplaceDescParams(text, passive)
    if passive.DescriptionParams ~= nil and passive.DescriptionParams ~= "" then
        --ECWarn("Found Params: "..Ext.Loca.GetTranslatedString(passive.DisplayName))
        local t = self:SplitStatString(passive.DescriptionParams)
        for k, v in pairs(t) do
            if tonumber(v) ~= nil then
                --ECDebug("Replacing [%d] with %s", k, v)
                text = text:gsub("%[["..k.."]%]", v)
            else
                local result = StatBS:SplitFunctionString(v)
                local parsed = StatBS:ParseKnownFunctions(result)
                if parsed ~= nil then
                    text = text:gsub("%[["..k.."]%]", parsed)
                else
                    text = text:gsub("%[["..k.."]%]", table.concat(result))
                end
            end
        end
    end
    return text
end

function StatBS:SplitFunctionString(str)
    -- Split the string based on delimiters using string.match
    local parts = {}
    for part in str:gmatch("[^(),]+") do
        part = part:match("^%s*(.-)%s*$")
        part = part:gsub("%%", "percent") -- safety escape
        table.insert(parts, part)
    end
    return parts
end
