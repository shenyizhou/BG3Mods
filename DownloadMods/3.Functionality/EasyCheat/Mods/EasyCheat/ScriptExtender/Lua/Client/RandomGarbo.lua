function StatBS:LeadingMinusPlusCheck(s)
    local sign = "+"
    local num = s or "0"
    for n in string.gmatch(s, "^-([0-9]-)+$") do
        -- negative
        sign = "-"
        num = n
    end
    for n in string.gmatch(s, "^+([0-9]-)+$") do
        -- positive
        num = n
    end
    for n in string.gmatch(s, "^([0-9]-)+$") do
        -- none, assume positive
        num = n
    end
    return sign..num
end

